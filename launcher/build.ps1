# Builds TvClean.apk with the plain SDK tools (aapt2, javac, d8, apksigner): no Gradle, no downloads.
# Needs JDK 17 and the Android SDK with platforms/android-34 and build-tools/34.0.0.
#   .\launcher\build.ps1 [-NoKeys]     -NoKeys: a build to share (no API keys, no city inside)
param([switch]$NoKeys)
$ErrorActionPreference = 'Continue'   # native tools write warnings to stderr; Check() looks at exit codes
$here = $PSScriptRoot
$sdk = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { "$env:LOCALAPPDATA\Android\Sdk" }
$bt = "$sdk\build-tools\34.0.0"
$jar = "$sdk\platforms\android-34\android.jar"
if (-not $env:JAVA_HOME) { $env:JAVA_HOME = (Get-ChildItem "C:\Program Files\Microsoft\jdk-17*" | Select-Object -First 1).FullName }
$java = "$env:JAVA_HOME\bin"
$out = "$here\build"

Remove-Item -Recurse -Force $out -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force "$out\res", "$out\classes", "$out\dex" | Out-Null

function Check($what) { if ($LASTEXITCODE -ne 0) { throw "$what failed" } }

& "$bt\aapt2.exe" compile --dir "$here\res" -o "$out\res\res.zip"; Check 'aapt2 compile'

# API keys go in the APK as assets/keys.properties, read from ..\tv\*.key (git ignores those files).
New-Item -ItemType Directory -Force "$out\keys" | Out-Null
$keys = @()
if (-not $NoKeys) {
    foreach ($name in 'tmdb', 'youtube') {
        $f = "$here\..\tv\$name.key"
        if (Test-Path $f) { $keys += "$name=$((Get-Content $f -Raw).Trim())" }
    }
    # The weather's city (tv\city.txt, git-ignored). Without it, the TV is located by its IP.
    if (Test-Path "$here\..\tv\city.txt") { $keys += "city=$((Get-Content "$here\..\tv\city.txt" -Raw -Encoding UTF8).Trim())" }
}
[IO.File]::WriteAllText("$out\keys\keys.properties", ($keys -join "`n"))

# What Home's own maintenance checks (Maintenance.java): the same rules tv\check.ps1 uses from the PC.
# The per-model lists go in as assets/device-<model>.txt; the app picks the one for its TV (Build.PRODUCT).
# Top level on purpose: aapt2 on Windows stores subfolders with a backslash the app cannot open.
. "$here\..\tv\common.ps1"
Get-ChildItem "$here\..\tv\devices\*.txt" | ForEach-Object { Copy-Item $_.FullName "$out\keys\device-$($_.Name)" }
$rules = @('# generated by build.ps1 from tv\common.ps1')
$rules += $HomePackages | ForEach-Object { "disable-home $_" }   # only once TvClean is the Home app
$rules += $NoBackground | ForEach-Object { "nobackground $_" }
foreach ($t in $Tuning) {
    if ($t[0] -eq 'device_config') { $rules += "device_config $($t[1]) $($t[2])" }
    else { $rules += "setting $($t[0]) $($t[1]) $($t[2])" }
}
$rules += 'appop-self GET_USAGE_STATS'
[IO.File]::WriteAllText("$out\keys\maintenance.txt", ($rules -join "`n"))

& "$bt\aapt2.exe" link -o "$out\base.apk" -I $jar --manifest "$here\AndroidManifest.xml" `
    -A "$here\assets" -A "$out\keys" -0 ttf --java "$out\gen" --min-sdk-version 26 --target-sdk-version 30 "$out\res\res.zip"; Check 'aapt2 link'

$sources = Get-ChildItem -Recurse "$here\src", "$out\gen" -Filter *.java | ForEach-Object FullName
& "$java\javac.exe" --release 8 -encoding UTF-8 -nowarn -classpath $jar -d "$out\classes" $sources 2>&1 | Write-Output; Check 'javac'

$classes = Get-ChildItem -Recurse "$out\classes" -Filter *.class | ForEach-Object FullName
& "$bt\d8.bat" --release --min-api 26 --lib $jar --output "$out\dex" $classes; Check 'd8'

Copy-Item "$out\base.apk" "$out\unsigned.apk"
Push-Location "$out\dex"
& "$java\jar.exe" uf "$out\unsigned.apk" classes.dex; Check 'add dex'
Pop-Location

& "$bt\zipalign.exe" -f -p 4 "$out\unsigned.apk" "$out\aligned.apk"; Check 'zipalign'

# The signing key lives outside the project, in the user's profile (TVCLEAN_KEYS overrides the folder):
# the keystore and its password file (random, made once). Updates must keep the same key, or Android
# refuses to install them over the app on the TV. The password is never on a command line.
$keys = if ($env:TVCLEAN_KEYS) { $env:TVCLEAN_KEYS } else { "$env:USERPROFILE\.tvclean" }
$ks = "$keys\tvclean.keystore"
$passFile = "$keys\keystore.pass"
if (-not (Test-Path $ks)) {
    New-Item -ItemType Directory -Force $keys | Out-Null
    $bytes = New-Object byte[] 24
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    [IO.File]::WriteAllText($passFile, ([Convert]::ToBase64String($bytes) -replace '[+/=]', 'x'))
    icacls $keys /inheritance:r /grant:r "${env:USERNAME}:(OI)(CI)F" | Out-Null
    & "$java\keytool.exe" -genkeypair -keystore $ks -storepass:file $passFile -keypass:file $passFile -alias tvclean `
        -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=TvClean" 2>$null; Check 'keytool'
}
# Key password = keystore password (PKCS12), so only --ks-pass: apksigner would read a second line otherwise.
& "$bt\apksigner.bat" sign --ks $ks --ks-pass "file:$passFile" --out "$out\TvClean.apk" "$out\aligned.apk"; Check 'apksigner'

$size = [math]::Round((Get-Item "$out\TvClean.apk").Length / 1KB)
Write-Output "OK: $out\TvClean.apk ($size KB)"
