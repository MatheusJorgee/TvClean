package com.tvclean.home;

import android.app.ActivityManager;
import android.content.Context;
import android.content.Intent;
import android.content.pm.PackageManager;
import android.content.pm.ResolveInfo;
import android.os.Build;

import java.io.BufferedReader;
import java.io.FileNotFoundException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * What tv/check.ps1 does from the PC, done by Home itself through LocalAdb: TCL's apps that switched
 * themselves back on go off again, settings Google reset are put back, and (on request) memory is freed.
 * The rules are assets/maintenance.txt (generated by build.ps1 from tv/common.ps1) plus this TV's list of
 * apps to keep off, assets/device-<Build.PRODUCT>.txt (from tv/devices in the repository), when there is one.
 */
final class Maintenance {
    static final class Report {
        final List<String> lines = new ArrayList<>();
        int fixed;
        long freedBytes;
        String error;
    }

    private Maintenance() {
    }

    /** Checks and fixes everything; with `freeMemory`, also closes every background app. Worker thread only. */
    static Report run(Context c, boolean freeMemory, int waitForUserMs) {
        Report r = new Report();
        long before = availMem(c);
        try (LocalAdb adb = LocalAdb.connect(c, waitForUserMs)) {
            List<String[]> rules = rules(c);
            Set<String> disabled = new HashSet<>();
            for (String l : adb.shell("pm list packages -d").split("\n")) disabled.add(l.replace("package:", "").trim());
            PackageManager pm = c.getPackageManager();
            for (String[] rule : rules) {
                switch (rule[0]) {
                    case "disable-home":   // a stock home screen: switched off only while TvClean is the Home app
                        if (!isDefaultHome(c)) break;
                        // fall through
                    case "disable": {
                        String pkg = rule[1];
                        if (disabled.contains(pkg)) break;
                        if (!adb.shell("pm path " + pkg).contains("package:")) break;   // not on this TV
                        adb.shell("pm disable-user --user 0 " + pkg);
                        r.fixed++;
                        r.lines.add("Desligado de novo: " + label(pm, pkg));
                        break;
                    }
                    case "nobackground": {
                        String pkg = rule[1];
                        if (!adb.shell("pm path " + pkg).contains("package:")) break;
                        if (adb.shell("cmd appops get " + pkg + " RUN_ANY_IN_BACKGROUND").contains("ignore")) break;
                        adb.shell("cmd appops set " + pkg + " RUN_ANY_IN_BACKGROUND ignore");
                        r.fixed++;
                        r.lines.add("Sem segundo plano de novo: " + label(pm, pkg));
                        break;
                    }
                    case "setting":   // setting <global|secure|system> <key> <value>
                        if (restore(adb, "settings", rule)) {
                            r.fixed++;
                            r.lines.add("Ajuste refeito: " + rule[2]);
                        }
                        break;
                    case "device_config":   // device_config <namespace> <key> <value>
                        if (restore(adb, "device_config", rule)) {
                            r.fixed++;
                            r.lines.add("Ajuste refeito: " + rule[2]);
                        }
                        break;
                    case "appop-self": {   // appop-self <op>: an op this app needs (usage access for "Continuar")
                        if (adb.shell("appops get " + c.getPackageName() + " " + rule[1]).contains("allow")) break;
                        adb.shell("appops set " + c.getPackageName() + " " + rule[1] + " allow");
                        r.fixed++;
                        r.lines.add("Permissão refeita: " + rule[1]);
                        break;
                    }
                    default:
                        break;
                }
            }
            if (freeMemory) {
                // Every process that is safe to kill (cached and background ones); the app on screen stays.
                adb.shell("am kill-all");
                adb.shell("pm trim-caches 256M");
            }
        } catch (Exception e) {
            r.error = e.getMessage() == null ? e.toString() : e.getMessage();
            return r;
        }
        if (freeMemory) {
            try {
                Thread.sleep(1500);   // let the system account for what was freed
            } catch (InterruptedException ignored) {
                Thread.currentThread().interrupt();
            }
            r.freedBytes = Math.max(0, availMem(c) - before);
        }
        return r;
    }

    static long availMem(Context c) {
        return memoryInfo(c).availMem;
    }

    static long totalMem(Context c) {
        return memoryInfo(c).totalMem;
    }

    private static ActivityManager.MemoryInfo memoryInfo(Context c) {
        ActivityManager.MemoryInfo mi = new ActivityManager.MemoryInfo();
        ((ActivityManager) c.getSystemService(Context.ACTIVITY_SERVICE)).getMemoryInfo(mi);
        return mi;
    }

    /** Puts a `<tool> <get|put>` setting back to the rule's value (rule = [kind, namespace, key, value]); true if it had drifted. */
    private static boolean restore(LocalAdb adb, String tool, String[] rule) throws Exception {
        String ns = rule[1], key = rule[2], want = rule[3];
        if (adb.shell(tool + " get " + ns + " " + key).trim().equals(want)) return false;
        adb.shell(tool + " put " + ns + " " + key + " " + want);
        return true;
    }

    /** Biggest memory users right now, as "Netflix  97 MB", from `dumpsys meminfo`. Worker thread only. */
    static List<String> topMemory(Context c, int count) {
        List<String> out = new ArrayList<>();
        try (LocalAdb adb = LocalAdb.connect(c, 0)) {
            String dump = adb.shell("dumpsys meminfo");
            int start = dump.indexOf("Total PSS by process:");
            if (start < 0) return out;
            PackageManager pm = c.getPackageManager();
            for (String line : dump.substring(start).split("\n")) {
                line = line.trim();
                int colon = line.indexOf("K: ");
                if (colon < 0) {
                    if (!out.isEmpty() && line.isEmpty()) break;
                    continue;
                }
                long kb = Long.parseLong(line.substring(0, colon).replace(",", "").replace(".", "").trim());
                String proc = line.substring(colon + 3);
                int sp = proc.indexOf(" (pid");
                if (sp > 0) proc = proc.substring(0, sp);
                if (proc.equals("system") || !proc.contains(".")) continue;   // the OS itself and native daemons
                String pkg = proc.contains(":") ? proc.substring(0, proc.indexOf(':')) : proc;
                out.add(label(pm, pkg) + "  " + (kb / 1024) + " MB");
                if (out.size() >= count) break;
            }
        } catch (Exception ignored) {
            // No debugging access: the panel simply shows no list.
        }
        return out;
    }

    /** Names for system parts whose own label is a package name or an abbreviation. */
    private static final Map<String, String> NAMES = new HashMap<>();

    static {
        NAMES.put("com.google.android.apps.mediashell", "Chromecast");
        NAMES.put("com.google.android.katniss", "Assistente (voz)");
        NAMES.put("com.android.systemui", "Interface do sistema");
        NAMES.put("com.tcl.tv", "TV (HDMI e antena)");
        NAMES.put("com.android.vending", "Play Store");
        NAMES.put("com.google.android.gms", "Google Play Services");
    }

    private static String label(PackageManager pm, String pkg) {
        String known = NAMES.get(pkg);
        if (known != null) return known;
        try {
            return String.valueOf(pm.getApplicationLabel(pm.getApplicationInfo(pkg, PackageManager.MATCH_DISABLED_COMPONENTS)));
        } catch (Exception e) {
            return pkg;
        }
    }

    private static List<String[]> rules(Context c) throws Exception {
        List<String[]> out = new ArrayList<>();
        for (String line : lines(c, "maintenance.txt")) out.add(line.split("\\s+"));
        try {
            for (String pkg : lines(c, "device-" + Build.PRODUCT + ".txt")) out.add(new String[]{"disable", pkg});
        } catch (FileNotFoundException none) {
            // No list for this model: only the generic rules.
        }
        return out;
    }

    /** An asset's lines, without comments (from #) and blank lines. */
    private static List<String> lines(Context c, String asset) throws Exception {
        List<String> out = new ArrayList<>();
        try (BufferedReader r = new BufferedReader(new InputStreamReader(c.getAssets().open(asset), StandardCharsets.UTF_8))) {
            String line;
            while ((line = r.readLine()) != null) {
                line = line.replaceAll("#.*$", "").trim();
                if (!line.isEmpty()) out.add(line);
            }
        }
        return out;
    }

    private static boolean isDefaultHome(Context c) {
        ResolveInfo home = c.getPackageManager().resolveActivity(
                new Intent(Intent.ACTION_MAIN).addCategory(Intent.CATEGORY_HOME), PackageManager.MATCH_DEFAULT_ONLY);
        return home != null && home.activityInfo != null && c.getPackageName().equals(home.activityInfo.packageName);
    }
}
